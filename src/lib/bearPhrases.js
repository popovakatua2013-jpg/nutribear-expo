// Случайная фраза из пула. random — для тестов (детерминизм).
export function pickPhrase(pool, random = Math.random) {
  if (!Array.isArray(pool) || pool.length === 0) return ''
  return pool[Math.floor(random() * pool.length) % pool.length]
}

// Какой тон выбрать по поведению пользователя.
//  loggedToday  — приём уже записан сегодня
//  missedToday  — время приёма уже прошло, а записи нет
//  missedStreak — сколько дней подряд ДО вчера этот приём пропускали
//  goodStreak   — сколько дней подряд ДО вчера приём записывали
//  style        — 'bear' (с характером) | 'spicy' (с перцем — влияет на
//                 пул фраз в mealPokeMessage) | 'soft' (мягко)
export function pickTone({ loggedToday = false, missedToday = false, missedStreak = 0, goodStreak = 0, style = 'bear' }) {
  if (style === 'soft') return 'soft'
  if (loggedToday) return 'praise'
  const missed = missedStreak + (missedToday ? 1 : 0)
  if (missed >= 2) return 'firm'
  if (missed === 1) return 'tease'
  if (goodStreak >= 3) return 'cheer'
  return 'soft'
}

// Готовый текст уведомления: { title, body }
// gender — 'm' | 'f' (пол пользователя из профиля). Токен {m:муж|жен}
// подставляет вариант по полу: «Куда пропал{m:|а}?» → «Куда пропал?» /
// «Куда пропала?», «{m:Сдался|Сдалась}?», «{m:Исчез|Исчезла} в закат».
// name  — имя из профиля (берём первое слово, до 24 символов — как в
//         редакторе профиля): «Катя, куда пропала?». Если имя не задано,
//         токен «{name}, » отрезается вместе с запятой, а первое слово
//         получает заглавную — тексты остаются прежними.
// По умолчанию мужской род без имени — совместимость со старым поведением.
export function mealPokeMessage({ mealId = 'lunch', tone = 'soft', streak = 0, gender = 'm', name = '', style = 'bear', random = Math.random }) {
  const label = MEAL_LABEL[mealId] || 'приём пищи'
  const fem = gender === 'f'
  const who = String(name || '').trim().split(/\s+/)[0].slice(0, 24)
  const fill = (s) => {
    let out = String(s).replace(/\{m:([^|}]*)\|([^}]*)\}/g, fem ? '$2' : '$1')
    // Имени нет — на месте «{name}, » ставим маркер \u0001: слово после
    // него получит заглавную. Имени нет ТОЛЬКО там, где был токен, —
    // остальные фразы сохраняют исходный регистр
    out = out.replace(/\{name\},\s*/g, who ? `${who}, ` : '\u0001')
    out = out.replaceAll('{name}', who)
    // {meal} в начале строки или после конца предложения — с заглавной:
    // «Обед в расписании…», «Ужин второй день мимо…». В середине фразы
    // («запиши {meal}») остаётся строчным
    const capLabel = label.charAt(0).toUpperCase() + label.slice(1)
    out = out.replace(/(^|[.!?…]\s*)\{meal\}/g, (m0, pre) => pre + capLabel)
    out = out.replaceAll('{meal}', label)
    out = out.replaceAll('{streak}', streak > 0 ? pluralRu(streak, ['день', 'дня', 'дней']) : '')
    if (!who) {
      // Капитализация на месте каждого маркера: «куда пропал?» →
      // «Куда пропал?». Цифры блокируют: «5 дней подряд» остаётся как есть
      out = out.replace(/\u0001([^а-яА-ЯёЁa-zA-Z0-9]*)([а-яёa-z])/g, (m0, pre, ch) => pre + ch.toUpperCase())
      out = out.split('\u0001').join('')
    }
    return out
  }

  if (tone === 'soft') {
    return { title: TITLES.soft[mealId] || '🐻 Напоминание', body: fill(POOLS.soft[mealId] || POOLS.soft.lunch) }
  }
  // Стиль «С перцем»: к медвежьему пулу добавляется дерзкая серия
  // (вторая серия пользователя) — механика тонов та же
  const basePool = POOLS[tone] || []
  const spicyExtra = style === 'spicy' && SPICY_POOLS[tone] ? SPICY_POOLS[tone] : []
  const pool = spicyExtra.length ? [...basePool, ...spicyExtra] : basePool
  return { title: fill(TITLES[tone] || '🐻 Напоминание'), body: fill(pickPhrase(pool, random)) }
}

