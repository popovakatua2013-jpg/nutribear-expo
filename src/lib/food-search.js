// Поиск по названию продукта — понимает русские формы слов и ё/е.
// Отзыв Кати 21.11: «не ищет йогуртов, творожков, батон, бургеры —
// строка поиска вообще ничего не ищет». Прежний поиск был строгой
// подстрокой (.includes): «йогуртов» не матчил «Йогурт натуральный»,
// «бургеры» не матчил «Бургер», «творожков» не матчил «Творог», а
// «варёная» не матчила «вареная» из-за ё/е.
// Теперь слово запроса совпадает со словом названия, если у них одна
// основа (первые 5 букв): «йогуртов» → «йогурт», «творожков» →
// «творог»/«творожок», «бургеры» → «бургер». Подстрока осталась как
// запасной путь — бренды в кавычках («Вязанка») и «3,2» внутри «3,2%».

// Разделители слов: пробелы, знаки препинания, кавычки, дефис
// («суп-пюре» → «суп» + «пюре» — находится и по «суп», и по «пюре»)
const WORD_SPLIT = /[\s,;.!?()[\]«»"'№:/\\+-]+/

// Длина основы: 5 букв хватает для продуктов («йогур», «творо», «бурге»)
// и безопасно — разные продукты на 5 первых буквах почти не совпадают
const STEM = 5

export function normalizeFoodText(s) {
  return (s || '').toLowerCase().replace(/ё/g, 'е')
}

function words(s) {
  return normalizeFoodText(s)
    .split(WORD_SPLIT)
    .filter(Boolean)
}

function wordMatch(nameWord, queryWord) {
  // Подстрока: «вязанка» внутри «колбаса варёная «Вязанка»»,
  // «3,2» внутри «3,2%», «омле» внутри «омлет»
  if (nameWord.includes(queryWord)) return true
  // Одна основа: «йогуртов» и «йогурт» → «йогур», «бургеры» и «бургер» → «бурге»
  return nameWord.slice(0, STEM) === queryWord.slice(0, STEM)
}

// true, если ВСЕ слова запроса есть в названии (порядок не важен:
// «йогурт питьевой» находит «Питьевой йогурт»). Пустой запрос —
// совпадение (полный список).
export function foodMatchesQuery(name, query) {
  const qWords = words(query)
  if (!qWords.length) return true
  const nameWords = words(name)
  return qWords.every((w) => nameWords.some((nw) => wordMatch(nw, w)))
}
