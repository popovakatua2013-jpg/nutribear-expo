// Письмо в поддержку через mailto (отзыв Кати 21.11: «чтобы отправлялось
// сообщение от пользователя сразу на почту… открыть свою почту и уже
// оттуда создать обращение»). Собирает URL вида
//   mailto:<адрес>?subject=<тема>&body=<текст>
// Тема и текст обязательно encodeURIComponent: в тексте бывают кириллица,
// переносы строк и знаки «&»/«?» — без кодирования они ломают параметры.
// Открывается через Linking.openURL: Android/iOS сами поднимают почтовое
// приложение пользователя с готовым черновиком — разработчику письмо
// приходит обычной почтой, пользователю не нужно ничего копировать.
export function supportMailtoUrl({ email, subject, body }) {
  return `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`
}
