// Темы оформления приложения (Premium-фича, задача Кати 23.11:
// «усилить Premium — оформление»; правка Кати 24.11: «при смене тем
// меняется частично вкладки и часть блоков» — палитра расширена
// акцентными токенами, жёстко зашитые цвета компонентов переведены
// на них). Правка Кати 24.11 («сделай в точности как на скрине»):
// старые блеклые темы («Чёрно-лимонная», «Хвоя», «Океан», «Слива»)
// заменены на ПЯТЬ ЯРКИХ НЕОНОВЫХ тем с макета — у каждой СВОЙ
// акцентный цвет (кнопки, тумблеры, пилюли, ссылки, рамки карточек
// светятся цветом темы), плюс светлая «Кремовая»:
//   «Неон-лайм» — чёрный фон + светящийся лайм;
//   «Неон-синий» — тёмно-синий фон + яркая лазурь;
//   «Неон-фиолетовый» — тёмно-фиолетовый фон + яркая орхидея;
//   «Неон-циан» — чёрно-бирюзовый фон + яркая бирюза;
//   «Приглушённая» — спокойный графитово-зелёный с шалфейным акцентом
//   (без «кислоты», правка Кати 25.11: «сделать еще приглушенную темы»);
//   «Кремовая» — светлая бежевая с янтарными акцентами.
//
// Правка Кати 26.11 («премиум-темы будут платные, закрой их для
// премиума; добавь одну бесплатную чёрно-белую без каких-либо
// эффектов»): Premium-гейтинг у неонов/«Приглушённой»/«Кремовой»
// подтверждён (premium: true — без подписки тап показывает
// подсказку, resolveThemeId возвращает «Классику»); добавлена
// БЕСПЛАТНАЯ «Чёрно-белая» — строгий монохром без свечения,
// градиентов и цветных ореолов: флаг plain: true отключает
// ореолы NeonCard, свечение SoftGlow и градиентные поверхности
// (NeonCard/GradientTile/CollapsibleCard рисуют плоскую карточку
// с тонкой рамкой), а accent == accentBright делает все оставшиеся
// градиенты приложения плоской заливкой — интерфейс выглядит
// строгим чёрно-белым, без «неона».
//
// Правка Кати 25.11 («цветные точки в блоках БЖУ — сделать по темам»,
// «блоки отчётов почти все не перекрашены — всё в одном стиле как и
// главная страница», «проверь замечания по всем темам»): у тем появились
// СЕМЕЙСТВА цветов — нутриенты (точки/иконки Б/Ж/У/клетчатки/сахара),
// метрики отчётов (шаги/калории/вода/сожжено/сон/вес) и семантика
// (хорошо/предупреждение/плохо). У неоновых тем это оттенки того же
// неона (всё приложение светится одним цветом, как на макете),
// у «Классики» — прежние фирменные цвета, у светлой «Кремовой» —
// тёмные насыщенные оттенки (контраст по WCAG AA на бежевом).
//
// Палитра живёт в tailwind.config.js через CSS-переменные --nb-*:
// класс bg-bear-bg компилируется в var(--nb-bg, <классика>) — поддеревья
// без переменных (окно «Мишка споткнулся», оверлеи без обёртки) остаются
// в «Классике», а не становятся прозрачными. Переменные прокидываются
// в корневом макете (app/_layout.jsx → src/lib/use-theme.js). Цвета
// в style-пропсах компонентов берутся из хука useThemeColors (там же) —
// они работают и вне обёртки с переменными.
//
// Файл чистый (без react-native и nativewind) — тестируется
// в __tests__/themes.test.js.

