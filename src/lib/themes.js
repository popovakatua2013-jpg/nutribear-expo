// Темы оформления приложения (Premium-фича, задача Кати 23.11:
// «усилить Premium — оформление»; правка Кати 24.11: «при смене тем
// меняется частично вкладки и часть блоков» — палитра расширена
// акцентными токенами, жёстко зашитые цвета компонентов переведены
// на них). Правка Кати 24.11 («сделай в точности как на скрине»):
// старые блеклые темы («Чёрно-лимонная», «Хвоя», «Океан», «Слива»)
// заменены на пять ЦВЕТНЫХ тем с макета — у каждой СВОЙ акцентный
// цвет (кнопки, тумблеры, пилюли, ссылки, рамки карточек подкрашены
// цветом темы), плюс светлая «Кремовая».
//
// Правка Кати 27.11 («сделай все премиум темы менее кричащими»;
// ориентир — скрин 3 с «Приглушённой»): ЧЕТЫРЕ неона переведены из
// кислотных акцентов (насыщенность s≈80–100%) в ПРИГЛУШЁННЫЕ ТОГО ЖЕ
// ТОНА (s≈26–33%; у «Приглушённой» s=22% — они стали её «роднёй»):
//   «Неон-лайм» → «Лайм»          #C9F31D → #B3C48C (оливково-лаймовый);
//   «Неон-синий» → «Лазурь»       #2E9EFF → #8AA9C4 (пыльная лазурь);
//   «Неон-фиолетовый» → «Орхидея» #C44BF8 → #AE9CC5 (пыльная сирень);
//   «Неон-циан» → «Бирюза»        #23E5C8 → #8FC2B8 (пыльная бирюза).
// Вместе с акцентом успокоены accentBright/Soft (без белых вспышек),
// текстовые тинты (менее цветные), рамки и свечения МЯГЧЕ:
// bodyLine/accentBorder 0.44–0.46/0.55 → 0.42/0.42, faint
// 0.12/0.18/0.24 → 0.10/0.15/0.20, strong 0.85 → 0.80. Текст НА
// акценте у всех тёмных тем теперь ТЁМНЫЙ (accentOn) — на светлой
// приглушённой поверхности белый не читался бы. Семья
// нутриентов/метрик (neonFamily) строится из акцентов и приглушается
// автоматически. Id тем НЕ менялись — выбор Кати в хранилище
// переживает переименование. Контрасты проверяет themes.test.js
// (sub/sub2/dim ≥ 4.5 по WCAG AA).
//
// Итоговый список Premium-тем:
//   «Лайм» — графитово-оливковый фон + оливково-лаймовый акцент;
//   «Лазурь» — тёмно-синий фон + пыльная лазурь;
//   «Орхидея» — тёмно-фиолетовый фон + пыльная сирень;
//   «Бирюза» — чёрно-бирюзовый фон + пыльная бирюза;
//   «Приглушённая» — спокойный графитово-зелёный с шалфейным акцентом
//   (без «кислоты», правка Кати 25.11: «сделать еще приглушенную темы»);
//   «Кремовая» — светлая бежевая с янтарными акцентами.
//
// Правка Кати 28.11 («мне не нравится как выглядит бело-черная тема.
// Давай бесплатную тему сделаем которая была до премиум темы —
// однотонная без эффектов и свечения»): бесплатная «Классика» — снова
// прежняя NAVY-палитра приложения (тёмно-синий фон, карточки, белый
// текст, фирменный фиолетовый #7B6CF6), восстановлена дословно из
// истории; чёрно-белая тема (26–27.11, id mono) удалена, её выборы
// переезжают на «Классику» (THEME_ROLL_FORWARD). Чтобы вид был
// ОДНОТОННЫМ, как до премиум-тем: plain: true (NeonCard/GradientTile/
// CollapsibleCard рисуют плоские карточки с тонкой рамкой, SoftGlow
// не рисуется) и accentBright == accent (#7B6CF6) — прочие градиенты
// приложения становятся плоской фирменной заливкой. Значки — прежние
// фирменные цвета (CLASSIC_FAMILY).
//
// Правка Кати 25.11 («цветные точки в блоках БЖУ — сделать по темам»,
// «блоки отчётов почти все не перекрашены — всё в одном стиле как и
// главная страница», «проверь замечания по всем темам»): у тем появились
// СЕМЕЙСТВА цветов — нутриенты (точки/иконки Б/Ж/У/клетчатки/сахара),
// метрики отчётов (шаги/калории/вода/сожжено/сон/вес) и семантика
// (хорошо/предупреждение/плохо). У неоновых тем это оттенки того же
// неона (всё приложение светится одним цветом, как на макете),
// у «Классики» — прежние фирменные цвета, у светлой «Кремовой» —
// тёмные насыщенные оттенки (контраст по WCAG AA на бежевом).
//
// Палитра живёт в tailwind.config.js через CSS-переменные --nb-*:
// класс bg-bear-bg компилируется в var(--nb-bg, <«Классика»>) — поддеревья
// без переменных (окно «Мишка споткнулся», оверлеи без обёртки) остаются
// в «Классике», а не становятся прозрачными. Переменные прокидываются
// в корневом макете (app/_layout.jsx → src/lib/use-theme.js). Цвета
// в style-пропсах компонентов берутся из хука useThemeColors (там же) —
// они работают и вне обёртки с переменными.
//
// Правка Кати 27.11 (история: «Классика будет бело-черная тема») —
// отменена правкой 28.11: чёрно-белая тема удалена, «Классика» снова
// прежняя navy (см. выше). Токены overlay/overlay2 — подложки-«поля»
// (вместо жёстких bg-white/*): у тёмных тем это белые тинты
// (как в исходном виде приложения), у светлых — тёмные.
//
// Файл чистый (без react-native и nativewind) — тестируется
// в __tests__/themes.test.js.

