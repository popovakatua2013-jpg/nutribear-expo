// Защита от двойного тапа на кнопках добавления еды.
// Урок из отзывов конкурента (скриншот Кати от 11.11, отзыв Елены:
// «сохраняются сразу три дублирующиеся записи, их сложно удалить»):
// второй тап по кнопке «Добавить» успевает сработать до перерисовки —
// и в дневнике оказываются дубли. Обёртка пропускает первое нажатие
// и молча игнорирует повторные в пределах окна (мс).

export function tapGuard(windowMs = 1200) {
  let last = 0
  return function run(fn) {
    const now = Date.now()
    if (now - last < windowMs) return false
    last = now
    fn()
    return true
  }
}
