// Порог вердиктов по системам (оси 0…100, желудок — по калориям к цели)
export const AUDIT_THRESHOLDS = {
  skinGood: 70, // ≥70 — сияет
  skinOk: 40,
  heartGood: 70,
  heartOk: 35,
  stomachGoodMin: 0.55, // коридор нормы калорий (доля от цели)
  stomachGoodMax: 1.05,
  stomachOver: 1.2,
  musclesGood: 70,
  musclesOk: 40,
  nervesGood: 3, // серия дней
  nervesOk: 1,
}

// Итоговый счёт аудита 0…100: среднее осей, энергия сворачивается
// к 100 (перебор не считается здоровьем — как energyHint в organism.js)
export function auditScore(axes = {}) {
  const e =
    axes.energy == null ? 0 : axes.energy <= 100 ? axes.energy : Math.max(0, 200 - axes.energy)
  const v = ((axes.hydration || 0) + (axes.protein || 0) + e + (axes.activity || 0)) / 4
  return Math.max(0, Math.min(100, Math.round(v)))
}

// Вердикт одной системы из данных дня. Желудок — по реальным калориям
// против цели: ось энергии в organism.js зажата в 0…100, перебор в ней
// потерялся бы — поэтому ratio считается из сырых значений.
function systemVerdict(key, { axes = {}, state = 'normal', streak = 0, kcal = 0, kcalGoal = 0 } = {}) {
  const t = AUDIT_THRESHOLDS
  switch (key) {
    case 'skin': {
      const v = axes.hydration || 0
      return v >= t.skinGood ? 'good' : v >= t.skinOk ? 'ok' : 'bad'
    }
    case 'stomach': {
      const ratio = kcalGoal > 0 ? kcal / kcalGoal : kcal > 0 ? Infinity : 0
      if (ratio > t.stomachOver) return 'bad'
      if (ratio > t.stomachGoodMax) return 'over'
      if (ratio >= t.stomachGoodMin) return 'good'
      return 'under'
    }
    case 'heart': {
      const v = axes.activity || 0
      return v >= t.heartGood ? 'good' : v >= t.heartOk ? 'ok' : 'bad'
    }
    case 'muscles': {
      const v = axes.protein || 0
      return v >= t.musclesGood ? 'good' : v >= t.musclesOk ? 'ok' : 'bad'
    }
    case 'nerves':
      return streak >= t.nervesGood ? 'good' : streak >= t.nervesOk ? 'ok' : 'bad'
    case 'immunity':
      return state === 'bloom' ? 'good' : state === 'normal' ? 'ok' : 'bad'
    default:
      return 'ok'
  }
}

