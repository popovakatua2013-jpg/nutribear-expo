// Остаток калорий на день в сводке «Съедено за сегодня».
// Два режима (переключатель «Ещё → Дневник питания», goals.countBurned):
// • строгий (по умолчанию — отзыв Кати: «строгий остаток по умолчанию»):
//   остаток = цель − съедено. Сожжённое НЕ возвращается — его оценка
//   (шаги, тренировки) часто завышена, а «съеденные обратно» калории
//   незаметно съедают реальный дефицит;
// • «с учётом сожжённых»: остаток = цель − съедено + сожжено —
//   активность возвращает калории, как в MyFitnessPal/Samsung Health.
// Цель не задана (0 или меньше) — остаток не считается (null).

export function remainderOf(target, consumed, burned = 0, countBurned = false) {
  if (!target || target <= 0) return null
  const base = target - consumed
  return Math.round(countBurned ? base + burned : base)
}
