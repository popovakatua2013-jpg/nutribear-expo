// Ложки для сыпучих продуктов (просьба Кати 28.11: «добавить в базу
// ч.л. ст.л. сыпучих продуктов, такие как крупы, сахарный песок и т.д.
// Например в 1 ч.л. сахара ?кал?»).
//
// Граммы «с горкой» — классическая таблица мер и весов:
//   1 ч.л. ≈ 5 мл + горка, 1 ст.л. ≈ 18 мл + горка.
// Калории никуда не дублируются — UI просто ставит grams = tsp/tbsp,
// и kcalForPortion пересчитывает из обычных КБЖУ на 100 г (у «Сахара-
// песок» 387 ккал/100 г → 1 ч.л. ≈ 8 г ≈ 31 ккал).
//
// Приоритет: точный id → шаблоны имени. Возвращаются граммы одной
// ложки; число ложек в интерфейсе умножает их на 1–2.

const SUGAR = { tsp: 8, tbsp: 25 } // сахарный песок, рафинад, пудра, фруктоза
const GROATS = { tsp: 8, tbsp: 25 } // сухие крупы: рис, гречка, пшено, перловка…
const FLOUR = { tsp: 8, tbsp: 25 } // мука пшеничная, ржаная, гречневая…
const FLAKES = { tsp: 6, tbsp: 12 } // лёгкие хлопья: овсяные, кукурузные, мюсли
const COCOA = { tsp: 6, tbsp: 15 } // какао-порошок
const STARCH = { tsp: 6, tbsp: 20 } // крахмал
const GELATIN = { tsp: 5, tbsp: 15 } // желатин
const POWDER = { tsp: 5, tbsp: 15 } // разрыхлитель, сода
const YEAST = { tsp: 4, tbsp: 12 } // сухие дрожжи
const COFFEE = { tsp: 3, tbsp: 8 } // кофе растворимый
const BREADCRUMBS = { tsp: 6, tbsp: 18 } // панировочные сухари
const MILK_POWDER = { tsp: 6, tbsp: 20 } // сухое молоко
const PROTEIN = { tsp: 10, tbsp: 30 } // протеин (мерная ложка ≈ 30 г)
const SEEDS = { tsp: 5, tbsp: 15 } // семена чиа/льна

// Точечные соответствия по id (база + брендовые файлы)
const BY_ID = {
  sugar: SUGAR,
  'xl-protein-powder': PROTEIN,
  'xl-cornflakes': FLAKES,
}

// Шаблоны имени. Порядок важен: частные правила раньше общих
// («овсяные хлопья (сухие)» — это хлопья 6/12, а не крупы 8/25;
// макароны/вермишель «(сухой)» ложками не меряем — исключаем явно)
const RULES = [
  [/сахарная пудра|фруктоза/, SUGAR],
  [/сахар-песок|сахар тростниковый|сахар-рафинад|сахарный песок/, SUGAR],
  [/мука/, FLOUR],
  [/манка|манная/, GROATS],
  [/какао[- ]порошок/, COCOA],
  [/крахмал/, STARCH],
  [/желатин/, GELATIN],
  [/разрыхлитель/, POWDER],
  [/сода/, POWDER],
  [/дрожжи/, YEAST],
  [/кофе растворимый|растворимый кофе/, COFFEE],
  [/панировочн/, BREADCRUMBS],
  [/сухое молоко|сухого молока/, MILK_POWDER],
  [/протеин/, PROTEIN],
  [/семена чиа|семена льна|семя льна/, SEEDS],
  // Макаронные изделия даже сухими ложками не меряют — пропускаем
  [
    /макарон|спагетти|вермишель|лапша|фарфалле|пенне|рожки|ракушки|бантики|перья|феттучине/,
    null,
  ],
  [/хлопья|геркулес|мюсли/, FLAKES],
  // «(сухой/сухая/сухое/сухие)» — сухие крупы и бобовые из брендовых файлов
  [/\(сух(ой|ая|ое|ие)\)/, GROATS],
]

// Граммы одной ч.л./ст.л. для продукта (или null — ложки не показываем).
// Учитывает уже заданные у продукта tsp/tbsp (база может переопределить)
export function spoonsFor(food) {
  if (!food) return null
  if (Number(food.tsp) > 0 && Number(food.tbsp) > 0) {
    return { tsp: Number(food.tsp), tbsp: Number(food.tbsp) }
  }
  const byId = BY_ID[food.id]
  if (byId) return byId
  const name = String(food.name || '').toLowerCase()
  for (const [re, sp] of RULES) {
    if (re.test(name)) return sp // null = «сухие макароны» — ложек нет
  }
  return null
}
